    /** 신장(키)은 「신장」이 콩팥과 같은 글자라 질환 낱말에서 키 말을 뺀다. */
    private val CONDITION_NOT = listOf("신장을", "신장은", "신장도", "신장바꿔", "신장수정", "신장을바꿔", "센티")

    fun detect(text: String, mode: ScreenMode = ScreenMode.COMMAND): SafetyKind? {
        val c = AssistantText.compact(text)
        if (c.isEmpty()) return null
        if (CRISIS.any { c.contains(it) }) return SafetyKind.CRISIS
        // 「다 끝내고 싶어」: 운동·루틴을 끝내는 말(재생 화면의 「끝내기」)이 아니면 마음 위기로 본다.
        if (c.contains("다끝내고싶") && CRISIS_NOT.none { c.contains(it) }) return SafetyKind.CRISIS
        if (EMERGENCY.any { c.contains(it) }) return SafetyKind.EMERGENCY
        if (isMedical(c)) return SafetyKind.MEDICAL
        // 「아파」만: 값 입력 칸(「허리 통증」을 질환으로 적는 중 등)이 아니면 응급 안내 — 놓치는 것보다 낫다.
        if (mode != ScreenMode.VALUE_CAPTURE && PAIN.containsMatchIn(c) && PAIN_NOT.none { c.contains(it) }) return SafetyKind.EMERGENCY
        return null
    }

    /** 이것만으로도 의료 판단을 묻는 말(부작용·용량은 묻는 것 자체가 판단 요청). */
    private val STRONG_MEDICAL = listOf("부작용", "상호작용", "복용량", "약용량", "몇알먹", "몇알씩")

    private fun isMedical(c: String): Boolean {
        if (STRONG_MEDICAL.any { c.contains(it) }) return true
        val drug = DRUG.any { c.contains(it) } || standaloneDrug(c)
        val condition = CONDITION.any { c.contains(it) } && CONDITION_NOT.none { c.contains(it) }
        val judge = JUDGE.any { c.contains(it) }
        return (drug || condition) && judge
    }

    /** 「약」 한 글자는 「약간」「예약」「요약」「약속」 속에 들어 있어 따로 거른다. 말 끝의 「약」(「이 약」)만 센다. */
    private fun standaloneDrug(c: String): Boolean {
        var cleaned = c
        DRUG_NOISE.forEach { cleaned = cleaned.replace(it, "") }
        return Regex("""(이|그|저|무슨|어떤|먹는|먹던|처방)약""").containsMatchIn(cleaned)
    }

    private val DRUG_NOISE = listOf("약간", "예약", "요약", "약속", "절약", "허약", "도약", "계약", "약점", "약해", "약하게")
